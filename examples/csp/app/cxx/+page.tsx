import { headers } from '@jk2908/solas/server'
import { cxx } from '@jk2908/cxx'

const [css, styles, href] = cxx`
	.card {
		padding: 1rem;
		border: 2px solid crimson;
		border-radius: 0.5rem;
	}

	.title {
		color: crimson;
		margin-top: 0;
	}
`

export const metadata = {
	title: 'cxx',
}

export default async function Page() {
	const nonce = (await headers()).get('x-nonce') ?? undefined

	return (
		<section>
			<h1>cxx</h1>

			{/* React 19 hoists this; it needs the document nonce under style-src. */}
			<style href={href} precedence="medium" nonce={nonce}>
				{css}
			</style>

			<div className={styles.card}>
				<h2 className={styles.title}>cxx under a nonce CSP</h2>
				<p>
					This style is generated by <code>cxx</code>. Navigate away and back; it must
					keep working on client navigation.
				</p>
			</div>
		</section>
	)
}
